-- 步骤1：商品字典表新增 category 字段
-- ------------------------------------------------------------
ALTER TABLE dbo.item_dictionary
ADD category INT DEFAULT 0;
GO

-- ------------------------------------------------------------
-- 步骤2：给历史商品分类打标
-- 说明：
--   1 = 助听器
--   2 = 耳膜
--   0 = 其他/尾差调整
--   请根据实际情况调整 WHERE 条件
-- ------------------------------------------------------------

-- 助听器商品
UPDATE dbo.item_dictionary
SET category = 1
WHERE name LIKE '%助听器%'
  AND name NOT LIKE '%尾差调整%';
GO

-- 耳膜商品
UPDATE dbo.item_dictionary
SET category = 2
WHERE name LIKE '%耳膜%'
  AND name NOT LIKE '%尾差调整%';
GO

-- 尾差调整商品先标记为其他（后续步骤再细分）
UPDATE dbo.item_dictionary
SET category = 0
WHERE name LIKE '%尾差调整%';
GO

-- ------------------------------------------------------------
-- 步骤3：处理尾差调整商品
-- 说明：
--   原来的尾差调整商品归为助听器尾差调整（category=1）
--   新增一个耳膜尾差调整商品（category=2）
-- ------------------------------------------------------------

-- 3.1 将现有尾差调整商品改为助听器尾差调整
-- 注意：如果存在多个尾差调整商品，请根据实际 id/code 调整 WHERE 条件
UPDATE dbo.item_dictionary
SET name = '助听器尾差调整',
    category = 1
WHERE name LIKE '%尾差调整%';
GO

